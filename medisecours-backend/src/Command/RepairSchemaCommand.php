    public function __construct(
        private readonly EntityManagerInterface $entityManager,
    ) {
        parent::__construct();
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $io = new SymfonyStyle($input, $output);
        $connection = $this->entityManager->getConnection();
        $failures = [];

        foreach (self::statements() as $index => $sql) {
            try {
                $connection->executeStatement($sql);
            } catch (\Throwable $e) {
                $failures[] = sprintf('[%d] %s — %s', $index, mb_substr(preg_replace('/\s+/', ' ', $sql), 0, 120), $e->getMessage());
            }
        }

        $total = \count(self::statements());
        $ok = $total - \count($failures);
        $io->text(sprintf('Schema repair: %d/%d statements applied.', $ok, $total));
        foreach ($failures as $failure) {
            $io->warning($failure);
        }

        return $failures === [] ? Command::SUCCESS : Command::FAILURE;
    }

