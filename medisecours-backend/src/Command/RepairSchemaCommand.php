/**
 * Réparation de schéma idempotente (boot production).
 *
 * L'entrypoint l'exécute AVANT doctrine:migrations:migrate : quel que soit
 * l'état de migration_versions (release marquée « migrée » sans que ses
 * objets n'existent, restauration partielle, deploy interrompu — spirale du
 * 12 octobre), cette relecture reconstruit tout ce que cette release exige :
 * tables carte (avis, suggestions, affiliations, SOS, équipes), préférences,
 * signatures numériques, circuit personnel (dossiers, soins, pharmacie).
 *
 * Chaque ordre est indépendant et rejouable (IF NOT EXISTS partout) : un
 * ordre en échec est journalisé et les suivants sont quand même tentés. Le
 * code de sortie est FAILURE si au moins un ordre a échoué (l'entrypoint ne
 * traite cela que comme un WARNING : le boot n'est jamais bloqué).
 */
#[AsCommand(
    name: 'app:repair-schema',
    description: 'Rejoue de façon idempotente tout le DDL exigé par cette release (ne bloque jamais le boot).',
)]
class RepairSchemaCommand extends Command
